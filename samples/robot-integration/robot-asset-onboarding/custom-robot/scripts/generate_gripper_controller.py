#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the ROS 2 gripper controller from <robot>.yaml.

Normal usage:
    python3 /obs/scripts/generate_gripper_controller.py \
      --yaml /data/workspace/eail/Assets/robots/robot_abc/abc.yaml

The input robot YAML is explicit. The script derives the sibling
<robot>_gripper_controller package and generated C++ output path from it.
It does not read SRDF directly. generate_robot_yaml.py has already normalized
SRDF open/close states into <robot>.yaml:

Single arm:
    topic_controller.hand

Dual arm:
    topic_controller.left_gripper
    topic_controller.right_gripper

Each gripper entry must contain:
    topic_name              low-level Float64MultiArray command topic
    gripper_command_topic   high-level Float64 width topic
    joint_names             authoritative output array order
    gripper_positions.open  joint -> position at width=0.1
    gripper_positions.close joint -> position at width=0.0

Any number of gripper joints is supported. Every joint is mapped independently:
    joint_position = k * width + b
where width=0.0 means close and width=0.1 means open.
"""

from __future__ import annotations

import argparse
import math
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional

import yaml


OPEN_WIDTH = 0.1
CLOSE_WIDTH = 0.0
GENERATED_MARKER = "AUTO-GENERATED BY generate_gripper_controller.py"


@dataclass(frozen=True)
class JointMapping:
    name: str
    open_value: float
    close_value: float
    k: float
    b: float


@dataclass(frozen=True)
class GripperConfig:
    role: str
    command_topic: str       # high-level Float64: 0.0 close, 0.1 open
    position_topic: str      # low-level Float64MultiArray
    joints: list[JointMapping]


def _normalize_topic(value: str, where: str) -> str:
    value = value.strip()
    if not value:
        raise ValueError(f"{where} must be a non-empty topic")
    return value if value.startswith("/") else f"/{value}"


def _finite_number(value: Any, where: str) -> float:
    if isinstance(value, bool):
        raise ValueError(f"{where} must be numeric, got bool")
    try:
        result = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{where} must be numeric, got {value!r}") from exc
    if not math.isfinite(result):
        raise ValueError(f"{where} must be finite, got {value!r}")
    return result


def _cpp_identifier(robot_name: str) -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", robot_name):
        raise ValueError(
            f"robot name {robot_name!r} is not valid for generated C++ identifiers"
        )
    return "".join(part.capitalize() for part in robot_name.split("_"))


def _cpp_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def _load_yaml(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise ValueError(
            f"robot yaml not found: {path}. Run generate_robot_yaml.py first."
        )
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise ValueError(f"invalid YAML in {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a YAML mapping")
    return data


def _parse_gripper(role: str, raw: Any, robot_yaml: Path) -> GripperConfig:
    prefix = f"{robot_yaml.name}: topic_controller.{role}"
    if not isinstance(raw, dict):
        raise ValueError(f"{prefix} must be a mapping")

    topic_name = raw.get("topic_name")
    if not isinstance(topic_name, str):
        raise ValueError(f"{prefix}.topic_name must be a string")
    position_topic = _normalize_topic(topic_name, f"{prefix}.topic_name")

    command_topic_raw = raw.get("gripper_command_topic")
    if not isinstance(command_topic_raw, str):
        raise ValueError(f"{prefix}.gripper_command_topic must be a string")
    command_topic = _normalize_topic(
        command_topic_raw, f"{prefix}.gripper_command_topic"
    )

    joint_names = raw.get("joint_names")
    if not isinstance(joint_names, list) or not joint_names:
        raise ValueError(f"{prefix}.joint_names must be a non-empty list")
    if not all(isinstance(name, str) and name.strip() for name in joint_names):
        raise ValueError(f"{prefix}.joint_names must contain non-empty strings")
    joint_names = [name.strip() for name in joint_names]
    if len(set(joint_names)) != len(joint_names):
        raise ValueError(f"{prefix}.joint_names contains duplicate joints")

    positions = raw.get("gripper_positions")
    if not isinstance(positions, dict):
        raise ValueError(f"{prefix}.gripper_positions must be a mapping")
    open_positions = positions.get("open")
    close_positions = positions.get("close")
    if not isinstance(open_positions, dict) or not isinstance(close_positions, dict):
        raise ValueError(
            f"{prefix}.gripper_positions.open and .close must both be mappings"
        )

    expected = set(joint_names)
    for label, values in (("open", open_positions), ("close", close_positions)):
        actual = set(values.keys())
        if actual != expected:
            raise ValueError(
                f"{prefix}.gripper_positions.{label} must exactly match joint_names; "
                f"missing={sorted(expected - actual)}, extra={sorted(actual - expected)}"
            )

    mappings: list[JointMapping] = []
    for joint_name in joint_names:
        open_value = _finite_number(
            open_positions[joint_name],
            f"{prefix}.gripper_positions.open.{joint_name}",
        )
        close_value = _finite_number(
            close_positions[joint_name],
            f"{prefix}.gripper_positions.close.{joint_name}",
        )
        k = (open_value - close_value) / (OPEN_WIDTH - CLOSE_WIDTH)
        b = close_value
        mappings.append(
            JointMapping(
                name=joint_name,
                open_value=open_value,
                close_value=close_value,
                k=k,
                b=b,
            )
        )

    return GripperConfig(
        role=role,
        command_topic=command_topic,
        position_topic=position_topic,
        joints=mappings,
    )


def _detect_layout(robot_yaml: Path) -> tuple[str, list[GripperConfig]]:
    cfg = _load_yaml(robot_yaml)
    topic_controller = cfg.get("topic_controller")
    if not isinstance(topic_controller, dict):
        raise ValueError(f"{robot_yaml.name}: topic_controller must be a mapping")

    has_hand = "hand" in topic_controller
    has_left = "left_gripper" in topic_controller
    has_right = "right_gripper" in topic_controller

    if has_hand and not has_left and not has_right:
        return "single", [
            _parse_gripper("hand", topic_controller["hand"], robot_yaml)
        ]

    if not has_hand and has_left and has_right:
        return "dual", [
            _parse_gripper("left_gripper", topic_controller["left_gripper"], robot_yaml),
            _parse_gripper("right_gripper", topic_controller["right_gripper"], robot_yaml),
        ]

    if has_left != has_right:
        missing = "right_gripper" if has_left else "left_gripper"
        raise ValueError(
            f"{robot_yaml.name}: dual gripper config is incomplete; missing {missing}"
        )

    if has_hand and (has_left or has_right):
        raise ValueError(
            f"{robot_yaml.name}: ambiguous gripper layout; use either hand or "
            "left_gripper + right_gripper"
        )

    raise ValueError(
        f"{robot_yaml.name}: no gripper config found. Expected topic_controller.hand "
        "or topic_controller.left_gripper + right_gripper."
    )


def _mapping_lines(joints: list[JointMapping], indent: str = "      ") -> str:
    return "\n".join(
        f"{indent}{joint.k:.12g} * width + {joint.b:.12g},  // {joint.name}: "
        f"open={joint.open_value:.12g}, close={joint.close_value:.12g}"
        for joint in joints
    )


def _single_cpp(robot_name: str, gripper: GripperConfig) -> str:
    class_name = _cpp_identifier(robot_name) + "GripperController"
    node_name = f"{robot_name}_gripper_controller"
    return f'''// {GENERATED_MARKER}. DO NOT EDIT MANUALLY.
#include <functional>
#include <memory>
#include <vector>

#include <rclcpp/rclcpp.hpp>
#include <std_msgs/msg/float64.hpp>
#include <std_msgs/msg/float64_multi_array.hpp>

class {class_name} : public rclcpp::Node
{{
public:
  {class_name}()
  : Node("{_cpp_string(node_name)}")
  {{
    gripper_joint_command_pub_ =
      this->create_publisher<std_msgs::msg::Float64MultiArray>(
        "{_cpp_string(gripper.position_topic)}", 10);

    gripper_command_sub_ =
      this->create_subscription<std_msgs::msg::Float64>(
        "{_cpp_string(gripper.command_topic)}", 10,
        std::bind(&{class_name}::GripperCallback, this, std::placeholders::_1));

    RCLCPP_WARN(this->get_logger(), "Ready to take new command for gripper!");
  }}

private:
  static constexpr double GRIPPER_MIN_WIDTH = {CLOSE_WIDTH:.12g};
  static constexpr double GRIPPER_MAX_WIDTH = {OPEN_WIDTH:.12g};

  rclcpp::Subscription<std_msgs::msg::Float64>::SharedPtr gripper_command_sub_;
  rclcpp::Publisher<std_msgs::msg::Float64MultiArray>::SharedPtr gripper_joint_command_pub_;

  std_msgs::msg::Float64MultiArray GenerateGripperJointFromWidth(double width)
  {{
    std_msgs::msg::Float64MultiArray message;
    message.data = {{
{_mapping_lines(gripper.joints)}
    }};
    return message;
  }}

  void GripperCallback(const std_msgs::msg::Float64::SharedPtr msg)
  {{
    double width = msg->data;
    if (width < GRIPPER_MIN_WIDTH) {{
      RCLCPP_ERROR(this->get_logger(),
        "The width must be >= %.2f, and will use %.2f instead",
        GRIPPER_MIN_WIDTH, GRIPPER_MIN_WIDTH);
      width = GRIPPER_MIN_WIDTH;
    }}
    if (width > GRIPPER_MAX_WIDTH) {{
      RCLCPP_ERROR(this->get_logger(),
        "The width must be <= %.2f, and will use %.2f instead",
        GRIPPER_MAX_WIDTH, GRIPPER_MAX_WIDTH);
      width = GRIPPER_MAX_WIDTH;
    }}

    gripper_joint_command_pub_->publish(GenerateGripperJointFromWidth(width));
  }}
}};

int main(int argc, char * argv[])
{{
  rclcpp::init(argc, argv);
  rclcpp::executors::MultiThreadedExecutor executor;
  auto node = std::make_shared<{class_name}>();
  executor.add_node(node);
  executor.spin();
  rclcpp::shutdown();
  return 0;
}}
'''


def _dual_cpp(robot_name: str, left: GripperConfig, right: GripperConfig) -> str:
    class_name = _cpp_identifier(robot_name) + "GripperController"
    node_name = f"{robot_name}_gripper_controller"
    return f'''// {GENERATED_MARKER}. DO NOT EDIT MANUALLY.
#include <functional>
#include <memory>
#include <vector>

#include <rclcpp/rclcpp.hpp>
#include <std_msgs/msg/float64.hpp>
#include <std_msgs/msg/float64_multi_array.hpp>

class {class_name} : public rclcpp::Node
{{
public:
  {class_name}()
  : Node("{_cpp_string(node_name)}")
  {{
    left_gripper_joint_command_pub_ =
      this->create_publisher<std_msgs::msg::Float64MultiArray>(
        "{_cpp_string(left.position_topic)}", 10);
    left_gripper_command_sub_ =
      this->create_subscription<std_msgs::msg::Float64>(
        "{_cpp_string(left.command_topic)}", 10,
        std::bind(&{class_name}::LeftGripperCallback, this, std::placeholders::_1));

    right_gripper_joint_command_pub_ =
      this->create_publisher<std_msgs::msg::Float64MultiArray>(
        "{_cpp_string(right.position_topic)}", 10);
    right_gripper_command_sub_ =
      this->create_subscription<std_msgs::msg::Float64>(
        "{_cpp_string(right.command_topic)}", 10,
        std::bind(&{class_name}::RightGripperCallback, this, std::placeholders::_1));

    RCLCPP_WARN(this->get_logger(), "Ready to take new command for gripper!");
  }}

private:
  static constexpr double GRIPPER_MIN_WIDTH = {CLOSE_WIDTH:.12g};
  static constexpr double GRIPPER_MAX_WIDTH = {OPEN_WIDTH:.12g};

  rclcpp::Subscription<std_msgs::msg::Float64>::SharedPtr left_gripper_command_sub_;
  rclcpp::Publisher<std_msgs::msg::Float64MultiArray>::SharedPtr left_gripper_joint_command_pub_;
  rclcpp::Subscription<std_msgs::msg::Float64>::SharedPtr right_gripper_command_sub_;
  rclcpp::Publisher<std_msgs::msg::Float64MultiArray>::SharedPtr right_gripper_joint_command_pub_;

  std_msgs::msg::Float64MultiArray GenerateLeftGripperJointFromWidth(double width)
  {{
    std_msgs::msg::Float64MultiArray message;
    message.data = {{
{_mapping_lines(left.joints)}
    }};
    return message;
  }}

  std_msgs::msg::Float64MultiArray GenerateRightGripperJointFromWidth(double width)
  {{
    std_msgs::msg::Float64MultiArray message;
    message.data = {{
{_mapping_lines(right.joints)}
    }};
    return message;
  }}

  void LeftGripperCallback(const std_msgs::msg::Float64::SharedPtr msg)
  {{
    double width = msg->data;
    if (width < GRIPPER_MIN_WIDTH) width = GRIPPER_MIN_WIDTH;
    if (width > GRIPPER_MAX_WIDTH) width = GRIPPER_MAX_WIDTH;
    left_gripper_joint_command_pub_->publish(
      GenerateLeftGripperJointFromWidth(width));
  }}

  void RightGripperCallback(const std_msgs::msg::Float64::SharedPtr msg)
  {{
    double width = msg->data;
    if (width < GRIPPER_MIN_WIDTH) width = GRIPPER_MIN_WIDTH;
    if (width > GRIPPER_MAX_WIDTH) width = GRIPPER_MAX_WIDTH;
    right_gripper_joint_command_pub_->publish(
      GenerateRightGripperJointFromWidth(width));
  }}
}};

int main(int argc, char * argv[])
{{
  rclcpp::init(argc, argv);
  rclcpp::executors::MultiThreadedExecutor executor;
  auto node = std::make_shared<{class_name}>();
  executor.add_node(node);
  executor.spin();
  rclcpp::shutdown();
  return 0;
}}
'''


def _safe_to_overwrite(path: Path) -> bool:
    if not path.exists():
        return True
    content = path.read_text(encoding="utf-8", errors="ignore").strip()
    return content in {"", "// define code"} or GENERATED_MARKER in content


def _print_mapping(label: str, cfg: GripperConfig) -> None:
    print(
        f"[INFO] {label}: {cfg.command_topic} -> {cfg.position_topic}; "
        f"joints={len(cfg.joints)}"
    )
    for joint in cfg.joints:
        print(
            f"[MAP] {joint.name}: open={joint.open_value:.12g}, "
            f"close={joint.close_value:.12g}, "
            f"joint={joint.k:.12g}*width+{joint.b:.12g}"
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--yaml",
        dest="robot_yaml",
        type=Path,
        required=True,
        help="generated <robot>.yaml path",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="optional generated .cpp output override",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite a non-generated C++ source",
    )
    args = parser.parse_args()

    try:
        robot_yaml = args.robot_yaml.expanduser().resolve()
        if not robot_yaml.is_file():
            raise ValueError(
                f"robot yaml not found: {robot_yaml}. "
                "Run generate_robot_yaml.py first."
            )

        robot_name = robot_yaml.stem
        if not robot_name:
            raise ValueError(f"cannot derive robot name from YAML path: {robot_yaml}")

        robot_root = robot_yaml.parent
        package_dir = robot_root / f"{robot_name}_gripper_controller"
        if not package_dir.is_dir() and args.output is None:
            raise ValueError(
                f"gripper package not found: {package_dir}. Run init_project.py first."
            )

        output_path = (
            args.output.expanduser().resolve()
            if args.output
            else package_dir / "src" / f"{robot_name}_gripper_controller.cpp"
        )

        layout_type, grippers = _detect_layout(robot_yaml)
        if layout_type == "single":
            content = _single_cpp(robot_name, grippers[0])
        else:
            content = _dual_cpp(robot_name, grippers[0], grippers[1])

        if output_path.exists() and not args.force and not _safe_to_overwrite(output_path):
            raise ValueError(
                f"refusing to overwrite user-authored source: {output_path}; "
                "use --force if replacement is intentional"
            )

        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(content, encoding="utf-8")

        print(f"[INPUT] robot yaml: {robot_yaml}")
        print(f"[CHECK] gripper package: {package_dir}")
        print(f"[OK] generated: {output_path}")
        print(
            f"[INFO] layout={layout_type}; high-level width protocol: "
            f"close={CLOSE_WIDTH}, open={OPEN_WIDTH}"
        )
        if layout_type == "single":
            _print_mapping("hand", grippers[0])
        else:
            _print_mapping("left_gripper", grippers[0])
            _print_mapping("right_gripper", grippers[1])

    except ValueError as exc:
        parser.error(str(exc))

if __name__ == "__main__":
    main()
