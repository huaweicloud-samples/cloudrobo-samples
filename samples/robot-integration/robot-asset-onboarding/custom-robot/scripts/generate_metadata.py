#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate/update metadata.json from the final robot YAML and MoveIt config.

Normal usage for a robot with gripper:
    python3 /obs/scripts/generate_metadata.py \
      --gripper-package-path /data/workspace/eail/Assets/robots/robot_abc/abc_gripper_controller

For a robot without a gripper, pass --robot-yaml instead.

Assumptions fixed by the current O3DE integration:
- exactly one JointTrajectoryController in ros2_controllers.yaml;
- exactly one MoveIt FollowJointTrajectory controller;
- both controller names must match;
- both controller joint *sets* must match (list order may differ);
- <robot>.yaml must use the normalized roles generated by generate_robot_yaml.py:
    single: arm [+ hand] [+ torso]
    dual:   left_arm + right_arm [+ left_gripper + right_gripper] [+ torso]

Topic sources:
- MoveIt feedback: moveit_controllers.yaml controller name + action_ns;
- arm/gripper low-level position topics: <robot>.yaml topic_controller.*.topic_name;
- /joint_states: platform fixed topic;
- high-level gripper topics: <robot>.yaml gripper_command_topic;
- torso position topic: <robot>.yaml topic_controller.torso.topic_name when present;
- camera topics: existing metadata.json camera_introduce[].topic;
- optional extra recording topics: --extra-topic.

Existing camera_introduce and unknown top-level metadata fields are preserved.
record_topic is rebuilt deterministically so stale generated topics do not accumulate.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Optional

import yaml


TRAJECTORY_TYPE = "joint_trajectory_controller/JointTrajectoryController"
FOLLOW_JOINT_TRAJECTORY = "FollowJointTrajectory"


def _load_yaml(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise ValueError(f"required YAML not found: {path}")
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise ValueError(f"invalid YAML in {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a YAML mapping")
    return data


def _load_existing_metadata(path: Path) -> dict[str, Any]:
    if not path.is_file() or path.stat().st_size == 0:
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"invalid existing JSON in {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data


def _normalize_topic(topic: str, where: str) -> str:
    topic = topic.strip()
    if not topic:
        raise ValueError(f"{where} must be a non-empty topic")
    return topic if topic.startswith("/") else f"/{topic}"


def _add_topic(result: list[str], topic: str) -> None:
    if topic not in result:
        result.append(topic)


def _validate_joint_list(value: Any, where: str) -> list[str]:
    if not isinstance(value, list) or not value:
        raise ValueError(f"{where} must be a non-empty list")
    if not all(isinstance(j, str) and j.strip() for j in value):
        raise ValueError(f"{where} must contain non-empty joint names")
    joints = [j.strip() for j in value]
    if len(joints) != len(set(joints)):
        raise ValueError(f"{where} contains duplicate joint names")
    return joints


def _parse_ros2_controller(path: Path) -> tuple[str, list[str]]:
    cfg = _load_yaml(path)
    params = cfg.get("controller_manager", {}).get("ros__parameters", {})
    if not isinstance(params, dict):
        raise ValueError(
            f"{path.name}: controller_manager.ros__parameters must be a mapping"
        )

    candidates: list[str] = []
    for name, entry in params.items():
        if not isinstance(entry, dict):
            continue
        if str(entry.get("type", "")).strip() == TRAJECTORY_TYPE:
            candidates.append(str(name))

    if len(candidates) != 1:
        raise ValueError(
            f"{path.name}: expected exactly one {TRAJECTORY_TYPE}, found {candidates}"
        )

    controller = candidates[0]
    controller_cfg = cfg.get(controller)
    if not isinstance(controller_cfg, dict):
        raise ValueError(f"{path.name}: missing top-level config for {controller}")
    ros_params = controller_cfg.get("ros__parameters")
    if not isinstance(ros_params, dict):
        raise ValueError(
            f"{path.name}: {controller}.ros__parameters must be a mapping"
        )
    joints = _validate_joint_list(
        ros_params.get("joints"),
        f"{path.name}: {controller}.ros__parameters.joints",
    )
    return controller, joints


def _parse_moveit_controller(path: Path) -> tuple[str, list[str], str]:
    cfg = _load_yaml(path)
    manager = cfg.get("moveit_simple_controller_manager")
    if not isinstance(manager, dict):
        raise ValueError(
            f"{path.name}: moveit_simple_controller_manager must be a mapping"
        )

    names = manager.get("controller_names")
    if not isinstance(names, list) or len(names) != 1 or not isinstance(names[0], str):
        raise ValueError(
            f"{path.name}: controller_names must contain exactly one controller"
        )
    controller = names[0].strip()
    if not controller:
        raise ValueError(f"{path.name}: controller name cannot be empty")

    entry = manager.get(controller)
    if not isinstance(entry, dict):
        raise ValueError(f"{path.name}: missing config for {controller}")
    controller_type = str(entry.get("type", "")).strip()
    if FOLLOW_JOINT_TRAJECTORY not in controller_type:
        raise ValueError(
            f"{path.name}: {controller}.type must be FollowJointTrajectory, "
            f"got {controller_type!r}"
        )

    joints = _validate_joint_list(
        entry.get("joints"), f"{path.name}: {controller}.joints"
    )
    action_ns = entry.get("action_ns")
    if not isinstance(action_ns, str) or not action_ns.strip():
        raise ValueError(f"{path.name}: {controller}.action_ns must be non-empty")
    action_ns = action_ns.strip().strip("/")

    return controller, joints, action_ns


def _validate_controller_contract(
    robot_yaml: dict[str, Any],
    robot_yaml_path: Path,
    ros2_controllers: Path,
    moveit_controllers: Path,
) -> tuple[str, list[str], str]:
    ros_name, ros_joints = _parse_ros2_controller(ros2_controllers)
    moveit_name, moveit_joints, action_ns = _parse_moveit_controller(moveit_controllers)

    if ros_name != moveit_name:
        raise ValueError(
            "controller name mismatch: "
            f"ros2_controllers={ros_name!r}, moveit_controllers={moveit_name!r}"
        )

    if set(ros_joints) != set(moveit_joints):
        ros_set = set(ros_joints)
        moveit_set = set(moveit_joints)
        raise ValueError(
            f"controller joint set mismatch for {ros_name}: "
            f"only_in_ros2={sorted(ros_set - moveit_set)}, "
            f"only_in_moveit={sorted(moveit_set - ros_set)}"
        )

    yaml_controller = robot_yaml.get("moveit_controller")
    if not isinstance(yaml_controller, str) or not yaml_controller.strip():
        raise ValueError(f"{robot_yaml_path.name}: moveit_controller must be non-empty")
    yaml_controller = yaml_controller.strip()
    if yaml_controller != ros_name:
        raise ValueError(
            f"{robot_yaml_path.name}: moveit_controller={yaml_controller!r} does not "
            f"match config controller {ros_name!r}"
        )

    return ros_name, ros_joints, action_ns


def _required_topic(role_cfg: Any, robot_yaml_path: Path, role: str) -> str:
    if not isinstance(role_cfg, dict):
        raise ValueError(
            f"{robot_yaml_path.name}: topic_controller.{role} must be a mapping"
        )
    topic = role_cfg.get("topic_name")
    if not isinstance(topic, str):
        raise ValueError(
            f"{robot_yaml_path.name}: topic_controller.{role}.topic_name must be a string"
        )
    return _normalize_topic(topic, f"topic_controller.{role}.topic_name")


def _required_gripper_command_topic(
    role_cfg: Any, robot_yaml_path: Path, role: str
) -> str:
    if not isinstance(role_cfg, dict):
        raise ValueError(
            f"{robot_yaml_path.name}: topic_controller.{role} must be a mapping"
        )
    topic = role_cfg.get("gripper_command_topic")
    if not isinstance(topic, str):
        raise ValueError(
            f"{robot_yaml_path.name}: topic_controller.{role}.gripper_command_topic "
            "must be a string"
        )
    return _normalize_topic(
        topic, f"topic_controller.{role}.gripper_command_topic"
    )


def _collect_robot_topics(
    robot_yaml: dict[str, Any],
    robot_yaml_path: Path,
    controller_name: str,
    action_ns: str,
) -> list[str]:
    topic_controller = robot_yaml.get("topic_controller")
    if not isinstance(topic_controller, dict):
        raise ValueError(f"{robot_yaml_path.name}: topic_controller must be a mapping")

    has_single = "arm" in topic_controller
    has_dual = "left_arm" in topic_controller or "right_arm" in topic_controller
    if has_single and has_dual:
        raise ValueError(
            f"{robot_yaml_path.name}: mixed single-arm and dual-arm topic roles"
        )

    topics: list[str] = []
    _add_topic(
        topics,
        f"/{controller_name}/{action_ns}/_action/feedback",
    )

    if has_single:
        _add_topic(
            topics,
            _required_topic(topic_controller.get("arm"), robot_yaml_path, "arm"),
        )
        _add_topic(topics, "/joint_states")

        if "hand" in topic_controller:
            _add_topic(
                topics,
                _required_topic(topic_controller.get("hand"), robot_yaml_path, "hand"),
            )
            _add_topic(
                topics,
                _required_gripper_command_topic(
                    topic_controller.get("hand"), robot_yaml_path, "hand"
                ),
            )
        if "torso" in topic_controller:
            _add_topic(
                topics,
                _required_topic(topic_controller.get("torso"), robot_yaml_path, "torso"),
            )
        return topics

    if "left_arm" not in topic_controller or "right_arm" not in topic_controller:
        raise ValueError(
            f"{robot_yaml_path.name}: expected either arm or left_arm + right_arm"
        )

    _add_topic(
        topics,
        _required_topic(topic_controller.get("left_arm"), robot_yaml_path, "left_arm"),
    )
    _add_topic(
        topics,
        _required_topic(topic_controller.get("right_arm"), robot_yaml_path, "right_arm"),
    )
    _add_topic(topics, "/joint_states")

    has_left_gripper = "left_gripper" in topic_controller
    has_right_gripper = "right_gripper" in topic_controller
    if has_left_gripper != has_right_gripper:
        raise ValueError(
            f"{robot_yaml_path.name}: dual gripper config must contain both "
            "left_gripper and right_gripper"
        )

    if has_left_gripper:
        _add_topic(
            topics,
            _required_topic(
                topic_controller.get("left_gripper"), robot_yaml_path, "left_gripper"
            ),
        )
        _add_topic(
            topics,
            _required_topic(
                topic_controller.get("right_gripper"), robot_yaml_path, "right_gripper"
            ),
        )

    if "torso" in topic_controller:
        _add_topic(
            topics,
            _required_topic(topic_controller.get("torso"), robot_yaml_path, "torso"),
        )

    if has_left_gripper:
        _add_topic(
            topics,
            _required_gripper_command_topic(
                topic_controller.get("left_gripper"), robot_yaml_path, "left_gripper"
            ),
        )
        _add_topic(
            topics,
            _required_gripper_command_topic(
                topic_controller.get("right_gripper"), robot_yaml_path, "right_gripper"
            ),
        )

    return topics


def _camera_topics(existing: dict[str, Any]) -> list[str]:
    cameras = existing.get("camera_introduce")
    if cameras is None:
        return []
    if not isinstance(cameras, list):
        raise ValueError("existing metadata.camera_introduce must be a list")

    result: list[str] = []
    for index, item in enumerate(cameras):
        if not isinstance(item, dict):
            raise ValueError(f"camera_introduce[{index}] must be an object")
        topic = item.get("topic")
        if not isinstance(topic, str):
            raise ValueError(f"camera_introduce[{index}].topic must be a string")
        _add_topic(
            result,
            _normalize_topic(topic, f"camera_introduce[{index}].topic"),
        )
    return result


def _resolve_metadata_inputs(args) -> tuple[str, Path, Path, Path, Path, Optional[Path]]:
    """Resolve explicit metadata inputs without scanning the workspace."""
    gripper_source: Optional[Path] = None

    if args.gripper_package_path is not None:
        gripper_package = args.gripper_package_path.expanduser().resolve()
        if not gripper_package.is_dir():
            raise ValueError(f"gripper package not found: {gripper_package}")

        suffix = "_gripper_controller"
        if not gripper_package.name.endswith(suffix) or gripper_package.name == suffix:
            raise ValueError(
                "--gripper-package-path must point to a <robot>_gripper_controller "
                f"package, got: {gripper_package}"
            )

        robot_name = gripper_package.name[:-len(suffix)]
        robot_root = gripper_package.parent
        robot_yaml_path = robot_root / f"{robot_name}.yaml"
        gripper_source = (
            gripper_package / "src" / f"{robot_name}_gripper_controller.cpp"
        )
        if not gripper_source.is_file():
            raise ValueError(
                f"gripper controller source not found: {gripper_source}. "
                "Run generate_gripper_controller.py first."
            )
    else:
        robot_yaml_path = args.robot_yaml.expanduser().resolve()
        if not robot_yaml_path.is_file():
            raise ValueError(f"robot yaml not found: {robot_yaml_path}")
        robot_name = robot_yaml_path.stem
        robot_root = robot_yaml_path.parent

    if not robot_yaml_path.is_file():
        raise ValueError(
            f"robot yaml not found: {robot_yaml_path}. Run generate_robot_yaml.py first."
        )

    config_dir = robot_root / f"{robot_name}_config" / "config"
    if not config_dir.is_dir():
        raise ValueError(f"MoveIt config directory not found: {config_dir}")

    ros2_controllers_path = config_dir / "ros2_controllers.yaml"
    moveit_controllers_path = config_dir / "moveit_controllers.yaml"
    if not ros2_controllers_path.is_file():
        raise ValueError(f"ros2_controllers.yaml not found: {ros2_controllers_path}")
    if not moveit_controllers_path.is_file():
        raise ValueError(f"moveit_controllers.yaml not found: {moveit_controllers_path}")

    output_path = (
        args.output.expanduser().resolve()
        if args.output
        else robot_root / "metadata.json"
    )

    return (
        robot_name,
        robot_yaml_path,
        ros2_controllers_path,
        moveit_controllers_path,
        output_path,
        gripper_source,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    source_group = parser.add_mutually_exclusive_group(required=True)
    source_group.add_argument(
        "--gripper-package-path",
        type=Path,
        help=(
            "<robot>_gripper_controller package path. For robots with grippers, "
            "this also verifies the generated controller source exists."
        ),
    )
    source_group.add_argument(
        "--robot-yaml",
        type=Path,
        help="<robot>.yaml path for robots without a gripper",
    )
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument(
        "--extra-topic",
        action="append",
        default=[],
        help="extra record topic; may be repeated",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="print metadata without writing metadata.json",
    )
    args = parser.parse_args()

    try:
        (
            robot_name,
            robot_yaml_path,
            ros2_controllers_path,
            moveit_controllers_path,
            output_path,
            gripper_source,
        ) = _resolve_metadata_inputs(args)

        robot_yaml = _load_yaml(robot_yaml_path)
        topic_controller = robot_yaml.get("topic_controller")
        has_gripper = isinstance(topic_controller, dict) and any(
            role in topic_controller
            for role in ("hand", "left_gripper", "right_gripper")
        )
        if has_gripper and gripper_source is None:
            raise ValueError(
                f"{robot_yaml_path.name} contains gripper configuration; use "
                "--gripper-package-path so the generated gripper controller is checked."
            )

        controller_name, controller_joints, action_ns = _validate_controller_contract(
            robot_yaml,
            robot_yaml_path,
            ros2_controllers_path,
            moveit_controllers_path,
        )

        existing = _load_existing_metadata(output_path)
        topics = _collect_robot_topics(
            robot_yaml,
            robot_yaml_path,
            controller_name,
            action_ns,
        )

        for topic in _camera_topics(existing):
            _add_topic(topics, topic)
        for topic in args.extra_topic:
            _add_topic(topics, _normalize_topic(topic, "--extra-topic"))

        metadata = dict(existing)
        metadata["robot_type"] = robot_name
        metadata["record_topic"] = topics

        text = json.dumps(metadata, ensure_ascii=False, indent=2) + "\n"
        print(text, end="")

        print(f"[INPUT] robot yaml: {robot_yaml_path}")
        print(f"[INPUT] MoveIt config: {moveit_controllers_path.parent}")
        if gripper_source is not None:
            print(f"[CHECK] gripper controller: {gripper_source}")

        if args.dry_run:
            print("[DRY-RUN] metadata.json not written")
            return

        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(text, encoding="utf-8")
        print(f"[OK] updated: {output_path}")
        print(f"[INFO] controller: {controller_name}")
        print(f"[INFO] ros2/moveit joint set: {len(controller_joints)} joints")

    except ValueError as exc:
        parser.error(str(exc))

if __name__ == "__main__":
    main()
